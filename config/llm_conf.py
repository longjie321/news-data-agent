# ============================================================
# 【这个文件干什么】
#   集中放"大模型"相关的配置和提示词。
#   以后想换模型、改提示词，只动这一个文件，不用去翻业务代码。
#
# 【注意】
#   API key 一律从 .env 读，绝不写死在代码里 —— 这是最基本的安全处理。
#   .env 已经被 .gitignore 排除，不会被提交到 git。
# ============================================================

import os

# 【导包说明】
#   os         —— 【标准库】Python 自带，不用 pip 装，负责读环境变量
#   load_dotenv —— 【三方库】python-dotenv 提供，把 .env 文件里的内容读成环境变量
from dotenv import load_dotenv

load_dotenv()

LLM_API_KEY = os.getenv("LLM_API_KEY", "")
LLM_BASE_URL = os.getenv("LLM_BASE_URL", "https://api.deepseek.com")

# .env 里配的模型名（默认 deepseek-chat）
LLM_MODEL = os.getenv("LLM_MODEL", "deepseek-chat")

# ------------------------------------------------------------
# 实际用于"工具调用"的模型
#
# 【有一个必须知道的硬约束】
#   DeepSeek 的推理模型（deepseek-reasoner）**不支持工具调用** ——
#   用它的话模型不会返回 tool_calls，整个智能体直接转不起来。
#
# 【为什么要"先取配置、再校验、不合格回退"，而不是直接写死】
#   原来的写法是 `LLM_MODEL_FOR_TOOLS = "deepseek-chat"` 写死，
#   于是 .env 里的 LLM_MODEL 成了摆设 —— 有人改了 .env 发现没反应，
#   得翻代码才知道是写死的，白折腾半天。（这种叫"死配置"，是个真坑）
#
#   现在改成：允许在 .env 里改，但如果配成不支持的模型
#     ① 启动就打印醒目警告（不用等第一个请求失败才知道）
#     ② 自动回退到 deepseek-chat，保证服务照样能用
# ------------------------------------------------------------
LLM_MODEL_FOR_TOOLS = LLM_MODEL

if "reasoner" in LLM_MODEL_FOR_TOOLS.lower():
    print(
        "⚠️  警告：.env 里的 LLM_MODEL = %s，它是推理模型、不支持工具调用。"
        "已自动回退到 deepseek-chat，请修改 .env。" % LLM_MODEL_FOR_TOOLS
    )
    LLM_MODEL_FOR_TOOLS = "deepseek-chat"

# ------------------------------------------------------------
# 系统提示词
#
# 这是"给模型立规矩"的地方。里面最重要的是第 2 条：
#   "工具返回什么就说什么，绝对不要编造数据"
# 因为大模型很爱"猜"数字，而数据查询场景里编数字是致命的。
# ------------------------------------------------------------
SYSTEM_PROMPT = (
    "你是一个新闻数据助手，可以通过调用工具来查询新闻数据库。\n"
    "\n"
    "请遵守下面的规则：\n"
    "1. 凡是涉及统计、排行、查找、数量这一类问题，必须先调用工具查询，不要凭印象直接回答。\n"
    "2. 工具返回什么就说什么，绝对不要编造数据；工具没查到就如实说没查到。\n"
    "3. 你的回答里如果出现具体数字（篇数、浏览量等），这个数字必须来自本轮工具调用的结果。\n"
    "4. 特别注意：不要因为上一轮刚回答过类似的问题，就直接推测答案。\n"
    "   每一轮涉及数据的问题都要重新调用工具查询，因为数据库内容随时可能变化，\n"
    "   上文的数字不代表当前的真实数据。\n"
    "5. 用简洁、准确的中文回答，涉及数字时要把数字说清楚。\n"
    "   注意：不要使用 Markdown 表格（用 | 和 --- 画的那种），因为页面不会渲染表格，\n"
    "   显示出来会是一堆竖线和横线，很难看。需要列多条内容时，用编号或短句逐条写。\n"
    "6. 如果工具返回了新闻标题或来源，可以引用出来作为依据。\n"
    "7. 一个问题可能需要多步才能答完：比如用户想看某篇新闻的具体内容，\n"
    "   你要先搜索或查排行拿到它的编号，再查详情。不要指望一次调用就拿到全部答案，\n"
    "   也不要因为第一轮没查到就放弃。\n"
    "   如果第一次搜索没有结果，自己换一个意思相近的关键词再试（最多换 2 次）\n"
    "   （比如“人工智能”没搜到就试“AI”“大模型”），\n"
    "   而不是直接把“没搜到、你自己换个词”推回给用户。\n"
    "   换过 2 次仍然没有，就如实说没找到，不要一直换下去。\n"
    "8. 如果用户只是在打招呼或者问和新闻数据无关的问题，正常聊天回答即可，不用调用工具。"
)
